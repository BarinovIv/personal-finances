import { describe, expect, it } from "vitest"
import { parseEntryLine, parseEntryLines } from "@fin/entry-line"

describe("строка ввода", () => {
  it.each([
    // строка, вид, сумма (копейки), описание, сдвиг даты
    ["футболка 1500", "expense", 150000, "футболка", 0],
    ["1500 футболка", "expense", 150000, "футболка", 0],
    ["кофе 250", "expense", 25000, "кофе", 0],
    ["футболка (1 500)", "expense", 150000, "футболка", 0],
    ["(1 500) футболка", "expense", 150000, "футболка", 0],
    ["телевизор (1 250 000)", "expense", 125000000, "телевизор", 0],
    ["молоко 99.90", "expense", 9990, "молоко", 0],
    ["молоко 99,90", "expense", 9990, "молоко", 0],
    ["молоко 99,9", "expense", 9990, "молоко", 0],
    ["обед 1.5к", "expense", 150000, "обед", 0],
    ["обед 1,2к", "expense", 120000, "обед", 0],
    ["куртка 2к", "expense", 200000, "куртка", 0],
    ["куртка 2К", "expense", 200000, "куртка", 0],
    ["кофе 250р", "expense", 25000, "кофе", 0],
    ["кофе 250 ₽", "expense", 25000, "кофе", 0],
    ["+зарплата 150000", "income", 15000000, "зарплата", 0],
    ["+подработка 12000", "income", 1200000, "подработка", 0],
    ["+ кэшбэк 350", "income", 35000, "кэшбэк", 0],
    ["+5000 подарок от мамы", "income", 500000, "подарок от мамы", 0],
    ["вчера такси 450", "expense", 45000, "такси", -1],
    ["Вчера такси 450", "expense", 45000, "такси", -1],
    ["такси вчера 450", "expense", 45000, "такси", -1],
    ["позавчера кино 800", "expense", 80000, "кино", -2],
    ["+вчера зарплата 95000", "income", 9500000, "зарплата", -1],
    ["2 кофе 500", "expense", 50000, "2 кофе", 0],
    ["  футболка   для  сына   1500 ", "expense", 150000, "футболка для сына", 0],
    ["Яндекс Go 350", "expense", 35000, "Яндекс Go", 0]
  ] as const)("«%s» → %s %i «%s»", (line, kind, amount, description, dateShift) => {
    expect(parseEntryLine(line)).toEqual({ kind, amount, description, dateShift, problems: [] })
  })

  it.each([
    ["футболка", ["no-amount"]],
    ["футболка 0", ["no-amount"]],
    ["1500", ["no-description"]],
    ["вчера 1500", ["no-description"]],
    ["+", ["no-amount", "no-description"]],
    ["", ["no-amount", "no-description"]]
  ] as const)("«%s» не сохраняется: %j", (line, problems) => {
    expect(parseEntryLine(line).problems).toEqual(problems)
  })

  it("одиночный разбор сохраняет разделители внутри описания", () => {
    expect(parseEntryLine('подарок; "мишка" 500')).toEqual({
      kind: "expense", amount: 50000, description: 'подарок; "мишка"', dateShift: 0, problems: []
    })
    expect(parseEntryLine("подарок, мишка 500").description).toBe("подарок, мишка")
    expect(parseEntryLine("подарок\nмишка 500").description).toBe("подарок мишка")
  })

  it("без суммы описание всё равно распознаётся", () => {
    expect(parseEntryLine("вчера футболка")).toEqual({
      kind: "expense",
      amount: null,
      description: "футболка",
      dateShift: -1,
      problems: ["no-amount"]
    })
  })
})

describe("несколько операций в строке", () => {
  const short = (line: string) =>
    parseEntryLines(line).map((p) => [p.kind, p.description, p.amount, p.dateShift, p.problems.join()])

  it("соседнее выражение сохраняет свою сумму и описание после умножения", () => {
    expect(short("200 * 3 карш шашлык 500 200 / 2 шаурма")).toEqual([
      ["expense", "карш", 60000, 0, ""],
      ["expense", "шашлык", 50000, 0, ""],
      ["expense", "шаурма", 10000, 0, ""]
    ])
  })

  it.each([
    ["кофе 250 99,90 молоко", [["кофе", 25000], ["молоко", 9990]]],
    ["кофе 250 99,90 молоко; такси 300", [["кофе", 25000], ["молоко", 9990], ["такси", 30000]]],
    ["кофе 250 99,90 молоко такси 300", [["кофе", 25000], ["молоко", 9990], ["такси", 30000]]],
    ["кофе 200*3 500 шашлык", [["кофе", 60000], ["шашлык", 50000]]],
    ["кофе 200 * 3 500 шашлык", [["кофе", 60000], ["шашлык", 50000]]],
    ["кофе 200/2 500 шашлык", [["кофе", 10000], ["шашлык", 50000]]],
    ["кофе 200 / 2 500 шашлык", [["кофе", 10000], ["шашлык", 50000]]],
    ["кофе 500 200/2 шаурма", [["кофе", 50000], ["шаурма", 10000]]],
    ["кофе 500 200 / 2 шаурма", [["кофе", 50000], ["шаурма", 10000]]],
    ["кофе 1 500 / 2", [["кофе", 75000]]],
    ["кофе 1 500/2 такси 300", [["кофе", 75000], ["такси", 30000]]],
    ["кофе 123 456; 300 такси", [["кофе", 12300], ["кофе", 45600], ["такси", 30000]]],
    ["кофе 123 456 такси 300", [["кофе", 12300], ["кофе", 45600], ["такси", 30000]]],
    ["бензин 95 3000 такси 300", [["бензин", 9500], ["бензин", 300000], ["такси", 30000]]],
    ["магазин 24/7 300 кофе 250", [["магазин 24/7", 30000], ["кофе", 25000]]],
    ["магазин 24/7 300", [["магазин 24/7", 30000]]],
    ["магазин 24/7 300 / 2", [["магазин 24/7", 15000]]],
    ["магазин 24/7 300/2", [["магазин 24/7", 15000]]],
    ["300/2 магазин 24/7", [["магазин 24/7", 15000]]],
    ["200 / 2 шаурма; шашлык 500", [["шаурма", 10000], ["шашлык", 50000]]]
  ] as const)("суммы и цифры в описании не перемешиваются: %s", (line, expected) => {
    expect(parseEntryLines(line).map((p) => [p.description, p.amount])).toEqual(expected)
    expect(parseEntryLines(line).every((p) => p.problems.length === 0)).toBe(true)
  })

  it("24/7 остаётся в описании и при недописанной следующей операции", () => {
    expect(short("магазин 24/7 300 такси")).toEqual([
      ["expense", "магазин 24/7", 30000, 0, ""],
      ["expense", "такси", null, 0, "no-amount"]
    ])
  })

  it.each([
    ["Шаурма 340 Шашлык 400 Такси 500", [["Шаурма", 34000], ["Шашлык", 40000], ["Такси", 50000]]],
    ["шаурма 340, шашлык 400; такси 500", [["шаурма", 34000], ["шашлык", 40000], ["такси", 50000]]],
    ["шаурма 340,такси 500", [["шаурма", 34000], ["такси", 50000]]],
    ["шаурма 340\nтакси 500", [["шаурма", 34000], ["такси", 50000]]],
    ["футболка 1 500 такси 300", [["футболка", 100], ["футболка", 50000], ["такси", 30000]]],
    ["кофе 250 ₽ такси 300", [["кофе", 25000], ["такси", 30000]]],
    ["кофе 250 руб такси 300", [["кофе", 25000], ["такси", 30000]]],
    ["обед 1.2к кофе 99,90", [["обед", 120000], ["кофе", 9990]]],
    ["Яндекс Go 350 кино 800", [["Яндекс Go", 35000], ["кино", 80000]]]
  ] as const)("«%s»", (line, expected) => {
    expect(parseEntryLines(line).map((p) => [p.description, p.amount])).toEqual(expected)
  })

  it.each([
    "футболка 1500",
    "1500 футболка",
    "2 кофе 500",
    "бензин АИ-95 3000",
    "такси 450 вчера",
    "+5000 подарок от мамы",
    "телевизор (1 250 000)"
  ])("«%s» остаётся одной операцией", (line) => {
    expect(parseEntryLines(line)).toEqual([parseEntryLine(line)])
  })

  it("у каждой операции свой плюс", () => {
    expect(short("+зарплата 150000 кофе 250 +кэшбэк 350")).toEqual([
      ["income", "зарплата", 15000000, 0, ""],
      ["expense", "кофе", 25000, 0, ""],
      ["income", "кэшбэк", 35000, 0, ""]
    ])
  })

  it("явная дата действует до следующей даты", () => {
    expect(short("вчера шаурма 340 позавчера кино 800 такси 500")).toEqual([
      ["expense", "шаурма", 34000, -1, ""],
      ["expense", "кино", 80000, -2, ""],
      ["expense", "такси", 50000, -2, ""]
    ])
    expect(short("шаурма 340 вчера такси 500")).toEqual([
      ["expense", "шаурма", 34000, 0, ""],
      ["expense", "такси", 50000, -1, ""]
    ])
  })

  it.each([";", ",", "\n"])("дата перед разделителем %j относится к следующей операции", (separator) => {
    expect(short(`кофе 100 вчера${separator} такси 200`)).toEqual([
      ["expense", "кофе", 10000, 0, ""],
      ["expense", "такси", 20000, -1, ""]
    ])
  })

  it("сегодня сбрасывает дату, а разделители сохраняют явно указанную дату", () => {
    expect(short("вчера кофе 100; такси 200 сегодня кино 300\nужин 400")).toEqual([
      ["expense", "кофе", 10000, -1, ""], ["expense", "такси", 20000, -1, ""],
      ["expense", "кино", 30000, 0, ""], ["expense", "ужин", 40000, 0, ""]
    ])
  })

  it("числа после разделителей повторяют описание и вид предыдущей операции", () => {
    expect(short("+вчера подработка 100, 200; 300\n400")).toEqual([
      ["income", "подработка", 10000, -1, ""], ["income", "подработка", 20000, -1, ""],
      ["income", "подработка", 30000, -1, ""], ["income", "подработка", 40000, -1, ""]
    ])
    expect(parseEntryLines("100; 200").every((entry) => entry.problems.includes("no-description"))).toBe(true)
  })

  it("недописанная последняя операция видна со своей проблемой", () => {
    expect(short("шаурма 340 такси")).toEqual([
      ["expense", "шаурма", 34000, 0, ""],
      ["expense", "такси", null, 0, "no-amount"]
    ])
  })

  it("недописанный доход после разделителя остаётся в предпросмотре", () => {
    expect(short("кофе 100; +")).toEqual([
      ["expense", "кофе", 10000, 0, ""],
      ["income", "", null, 0, "no-amount,no-description"]
    ])
  })

  it("дата в отдельном среднем фрагменте действует только на следующие операции", () => {
    expect(short("кофе 100; вчера; такси 200")).toEqual([
      ["expense", "кофе", 10000, 0, ""], ["expense", "такси", 20000, -1, ""]
    ])
  })

  it("цифры перед описанием сохраняются после явного разделителя", () => {
    expect(short("кофе 100; 2 кофе 500")).toEqual([
      ["expense", "кофе", 10000, 0, ""], ["expense", "2 кофе", 50000, 0, ""]
    ])
  })

  it("пустые куски между разделителями пропускаются", () => {
    expect(short("шаурма 340,, такси 500,")).toEqual([
      ["expense", "шаурма", 34000, 0, ""],
      ["expense", "такси", 50000, 0, ""]
    ])
    expect(parseEntryLines("")).toEqual([parseEntryLine("")])
  })
})

describe("калькулятор в строке ввода", () => {
  it("складывает сумму и повторяет описание для следующей суммы через пробел", () => {
    expect(parseEntryLines("каршеринг 150 + 150 400")).toEqual([
      { kind: "expense", amount: 30000, description: "каршеринг", dateShift: 0, problems: [] },
      { kind: "expense", amount: 40000, description: "каршеринг", dateShift: 0, problems: [] }
    ])
  })

  it.each([
    ["кофе 100+200+300", [60000]],
    ["100 + 200 + 300 кофе", [60000]],
    ["кофе 200*3", [60000]],
    ["200 * 3 кофе", [60000]],
    ["кофе 400/2", [20000]],
    ["400 / 2 кофе", [20000]],
    ["кофе 1000-330", [67000]],
    ["1000 - 330 кофе", [67000]],
    ["кофе 99,90 / 2", [4995]],
    ["кофе 300 * 1", [30000]],
    ["кофе (150 400) / 2", [7520000]],
    ["кофе 200 / (2 500)", [8]],
    ["кофе 200 * 1,5", [30000]],
    ["кофе 200 - 100 - 50", [5000]],
    ["кофе (100 + (50 * 2)) / 2", [10000]],
    ["кофе 0,03 / 2", [2]]
  ] as const)("сохраняет значения и число операций: %s", (line, amounts) => {
    expect(parseEntryLines(line)).toEqual(amounts.map((amount) => ({
      kind: "expense", amount, description: "кофе", dateShift: 0, problems: []
    })))
  })

  it("учитывает приоритет смешанных действий", () => {
    expect(parseEntryLine("кофе 100 + 50 * 2")).toEqual({
      kind: "expense", amount: 20000, description: "кофе", dateShift: 0, problems: []
    })
  })

  it("скобки меняют порядок вычисления", () => {
    expect(parseEntryLine("кофе (100 + 50) * 2").amount).toBe(30000)
  })

  it("принимает знаки чисел внутри выражения", () => {
    expect(parseEntryLine("кофе 100 * -2 + +300").amount).toBe(10000)
  })

  it("объединяет короткую первую группу тысяч только в выражении", () => {
    expect(parseEntryLine("кофе 1 500 * 2").amount).toBe(300000)
    expect(parseEntryLine("кофе 1000 - 1 500").problems).toEqual(["invalid-calculation"])
    expect(parseEntryLines("кофе 1 500").map((entry) => entry.amount)).toEqual([100, 50000])
  })

  it.each([
    ["кофе 200 * 0.125", 2500],
    ["кофе 200 / 0.125", 160000],
    ["кофе 200 * 0,0001", 2],
    ["кофе 1.500", 150000],
    ["кофе 100 / 3 * 3", 10000],
    ["кофе 0,57 / 2", 29],
    ["кофе 0,29 * 1,5", 44],
    ["кофе 1 * 1.005", 101],
    ["кофе 100 - 200 + 300", 20000]
  ])("дробные множители и округление только после вычисления: %s", (line, amount) => {
    expect(parseEntryLine(line).amount).toBe(amount)
  })

  it("суммы без описания наследуют доход, а новое описание начинает расход", () => {
    expect(parseEntryLines("+подработка 150 + 150 400 кофе 200").map((entry) => [entry.kind, entry.description, entry.amount])).toEqual([
      ["income", "подработка", 30000], ["income", "подработка", 40000], ["expense", "кофе", 20000]
    ])
  })

  it("одиночный разбор не отбрасывает следующие суммы", () => {
    expect(parseEntryLine("кофе 100 200")).toEqual({
      kind: "expense", amount: null, description: "кофе", dateShift: 0, problems: ["invalid-calculation"]
    })
  })

  it("выражение в скобках через пробел начинает следующую сумму", () => {
    expect(parseEntryLines("кофе 100 (200 + 100) 400").map((entry) => [entry.description, entry.amount, entry.problems])).toEqual([
      ["кофе", 10000, []], ["кофе", 30000, []], ["кофе", 40000, []]
    ])
    expect(parseEntryLines("кофе 100 (200 + 300")[1]?.problems).toEqual(["invalid-calculation"])
  })

  it("отдельный плюс перед описанием обозначает следующий доход", () => {
    expect(parseEntryLines("кофе 200 + подработка 500").map((entry) => [entry.kind, entry.description, entry.amount, entry.problems])).toEqual([
      ["expense", "кофе", 20000, []], ["income", "подработка", 50000, []]
    ])
  })

  it("очень глубокие скобки остаются ошибкой ввода вместо падения предпросмотра", () => {
    const line = `кофе ${"(".repeat(5000)}100${")".repeat(5000)}`
    expect(parseEntryLines(line)).toEqual([
      { kind: "expense", amount: null, description: "кофе", dateShift: 0, problems: ["invalid-calculation"] }
    ])
  })

  it.each(["кофе 1 500 ₽ * 2", "кофе 1 500р * 2"])("обозначение рублей не мешает объединить разряды: %s", (line) => {
    expect(parseEntryLines(line)).toEqual([
      { kind: "expense", amount: 300000, description: "кофе", dateShift: 0, problems: [] }
    ])
  })

  it.each(["кофе 1 500 + подработка 200", "кофе 1 500 +подработка 200"])("плюс дохода не объединяет предыдущие суммы в разряды: %s", (line) => {
    expect(parseEntryLines(line).map((entry) => [entry.kind, entry.description, entry.amount])).toEqual([
      ["expense", "кофе", 100], ["expense", "кофе", 50000], ["income", "подработка", 20000]
    ])
  })

  it.each(["кофе 100(200)", "кофе 100 (200)300", "кофе (100)(200)"])("между соседними компактными выражениями нужен знак: %s", (line) => {
    expect(parseEntryLines(line).some((entry) => entry.problems.includes("invalid-calculation"))).toBe(true)
  })

  it("умножение не разворачивает операции и не ограничивает множитель числом повторов", () => {
    expect(parseEntryLines("кофе 300*1001")).toEqual([
      { kind: "expense", amount: 30030000, description: "кофе", dateShift: 0, problems: [] }
    ])
  })

  it.each([
    "кофе 200/0", "кофе 0,01 / 3", "кофе 200-200", "кофе 200-300",
    "кофе 200*0", "кофе 200*9999999999999999", "кофе (200 + 100", "кофе 200 + * 100",
    "кофе 200 + 100)", "кофе 200 /", "кофе ()", "кофе 200 +"
  ])("не теряет некорректное выражение: %s", (line) => {
    expect(parseEntryLines(line)).toEqual([{
      kind: "expense", amount: null, description: "кофе", dateShift: 0, problems: ["invalid-calculation"]
    }])
  })

  it("сочетает десятичную запятую, явные разделители, общую дату и отдельный плюс дохода", () => {
    expect(parseEntryLines("вчера 99,90 / 2 кофе; +позавчера 200 / 2 подработка, такси 300")).toEqual([
      { kind: "expense", amount: 4995, description: "кофе", dateShift: -1, problems: [] },
      { kind: "income", amount: 10000, description: "подработка", dateShift: -2, problems: [] },
      { kind: "expense", amount: 30000, description: "такси", dateShift: -2, problems: [] }
    ])
  })
})

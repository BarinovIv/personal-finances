import { memoryStore, openLedger } from "@fin/ledger"
import { createAuthApi, createSync } from "@fin/sync"
import { expect, it } from "vitest"
import { inProcessServer, PASSWORD, testClock } from "./support"

it("полная копия возвращает уже синхронизированные данные на пустой сервер и другое устройство", async () => {
  const clock = testClock("2026-10-18T12:00:00+03:00")
  const oldServer = await inProcessServer(clock)
  const server = await inProcessServer(clock)
  const store = memoryStore()
  const source = await openLedger({ store, now: clock.now })
  const oldDevice = oldServer.device()
  const device = server.device()
  const otherDevice = server.device()
  const other = await openLedger({ store: memoryStore(), now: clock.now })
  const oldSync = createSync({ ledger: source, transport: oldDevice.transport })
  const sync = createSync({ ledger: source, transport: device.transport })
  const otherSync = createSync({ ledger: other, transport: otherDevice.transport })
  try {
    expect((await createAuthApi(oldDevice.transport).login(PASSWORD)).ok).toBe(true)
    expect((await createAuthApi(device.transport).login(PASSWORD)).ok).toBe(true)
    expect((await createAuthApi(otherDevice.transport).login(PASSWORD)).ok).toBe(true)
    const category = await source.addCategory("expense", "Поездки")
    if (!category.ok) throw new Error(category.problem)
    expect((await source.setCategoryLimit(category.category.id, 1000000)).ok).toBe(true)
    const expense = await source.submit("билет 5000", { categoryId: category.category.id })
    if (!expense.ok) throw new Error("Не удалось добавить расход")
    expect((await source.addRefund(expense.operation.id, { amount: 100000 })).ok).toBe(true)
    expect((await source.submit("+зарплата 100000")).ok).toBe(true)
    const goal = await source.addGoal({ name: "Отпуск", target: 5000000, deadline: "2027-06-01" })
    if (!goal.ok) throw new Error(goal.problem)
    expect((await source.addMovement({ kind: "saved", goalId: goal.goal.id, amount: 500000 })).ok).toBe(true)
    expect((await source.addMovement({ kind: "withdrawn", goalId: goal.goal.id, amount: 100000 })).ok).toBe(true)
    const lent = await source.addMovement({ kind: "lent", person: "Петя", amount: 200000 })
    const borrowed = await source.addMovement({ kind: "borrowed", person: "Маша", amount: 300000 })
    if (!lent.ok || !borrowed.ok) throw new Error("Не удалось добавить долг")
    expect((await source.addMovement({ kind: "repaid-to-me", debtId: lent.operation.id, amount: 50000 })).ok).toBe(true)
    expect((await source.addMovement({ kind: "repaid-by-me", debtId: borrowed.operation.id, amount: 100000 })).ok).toBe(true)
    expect((await source.makeRecurring(expense.operation.id, {
      description: "билет", amount: 500000, categoryId: category.category.id, dayOfMonth: 20
    })).ok).toBe(true)
    expect((await source.setPaydays([5, 20])).ok).toBe(true)
    expect((await source.setTimeZone("Asia/Tbilisi")).ok).toBe(true)
    await source.setDashboardMode("month")
    expect(await oldSync.syncNow()).toBe("ok")
    expect(source.pendingChanges()).toEqual([])
    expect(source.sync.cursor()).toBeGreaterThan(0)

    const backup = await source.exportBackup()
    expect(await source.importBackup(backup)).toMatchObject({ ok: true, added: 0, updated: 0 })
    expect(source.sync.cursor()).toBe(0)
    expect(source.pendingChanges().length).toBeGreaterThan(0)
    // Очередь восстановления должна пережить закрытие приложения до первого обмена.
    const reopened = await openLedger({ store, now: clock.now })
    expect(reopened.sync.cursor()).toBe(0)
    expect(reopened.pendingChanges()).toEqual(source.pendingChanges())
    expect(await sync.syncNow()).toBe("ok")
    expect(source.pendingChanges()).toEqual([])
    expect(await otherSync.syncNow()).toBe("ok")
    expect(other.days()).toEqual(source.days())
    expect(other.categories("expense")).toEqual(source.categories("expense"))
    expect(other.categories("income")).toEqual(source.categories("income"))
    expect(other.goals()).toEqual(source.goals())
    expect(other.recurring()).toEqual(source.recurring())
    expect(other.settings()).toEqual(source.settings())
    expect(other.refunds(expense.operation.id)).toEqual(source.refunds(expense.operation.id))
    expect(other.repayments(lent.operation.id)).toMatchObject({ remaining: 150000 })
    expect(other.repayments(borrowed.operation.id)).toMatchObject({ remaining: 200000 })
    expect(other.goalSavings(goal.goal.id)).toBe(400000)

    expect(await source.importBackup(backup)).toMatchObject({ ok: true, added: 0, updated: 0 })
    expect(await sync.syncNow()).toBe("ok")
    expect(await otherSync.syncNow()).toBe("ok")
    expect(other.days()).toEqual(source.days())
    expect(other.days().flatMap((day) => day.items)).toHaveLength(9)
    const fresh = await openLedger({ store: memoryStore(), now: clock.now })
    expect(await fresh.importBackup(backup)).toMatchObject({ ok: true })
    expect(fresh.days()).toEqual(source.days())
    expect(fresh.dashboardMode()).toBe("month")
  } finally {
    await oldSync.stop()
    await sync.stop()
    await otherSync.stop()
    await oldServer.close()
    await server.close()
  }
})
